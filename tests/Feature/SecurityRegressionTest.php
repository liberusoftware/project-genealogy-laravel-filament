it('prevents privilege escalation on admin panel access and TeamResource access', function (): void {
    $regular = User::factory()->create();
    $admin = User::factory()->create();
    $team = Team::factory()->create(['user_id' => $admin->id]);
    $admin->forceFill(['current_team_id' => $team->id])->save();

    setPermissionsTeamId($team->id);
    $superAdminRole = Role::firstOrCreate(['name' => 'super_admin', 'guard_name' => 'web', 'team_id' => $team->id]);
    $admin->assignRole($superAdminRole);

    $adminPanel = Filament::getPanel('admin');

    expect($regular->canAccessPanel($adminPanel))->toBeFalse()
        ->and($admin->canAccessPanel($adminPanel))->toBeTrue();

    $this->actingAs($regular);
    expect(TeamResource::canAccess())->toBeFalse();

    $this->actingAs($admin);
    expect(TeamResource::canAccess())->toBeTrue();
});

it('blocks mass assignment of sensitive fields and hides secrets/PII from serialization', function (): void {
    $user = new User();
    $user->fill([
        'name' => 'Safe Name',
        'email' => 'pii@example.com',
        'password' => 'plain-or-hashed',
        'is_premium' => true,
        'current_team_id' => 999,
        'trial_ends_at' => now()->addYears(10),
        'premium_started_at' => now(),
    ]);

    expect($user->is_premium)->toBeNull()
        ->and($user->current_team_id)->toBeNull()
        ->and($user->trial_ends_at)->toBeNull()
        ->and($user->premium_started_at)->toBeNull();

    $serializedUser = $user->toArray();
    expect($serializedUser)->not->toHaveKeys([
        'password',
        'remember_token',
        'two_factor_secret',
        'two_factor_recovery_codes',
        'email',
        'email_verified_at',
    ]);

    $account = new ConnectedAccount();
    $account->fill([
        'user_id' => 999,
        'provider' => 'github',
        'provider_id' => 'gh-1',
        'token' => 'secret-oauth-token',
        'secret' => 'secret-oauth-secret',
        'refresh_token' => 'secret-refresh-token',
    ]);

    expect($account->user_id)->toBeNull()
        ->and($account->toArray())->not->toHaveKeys(['token', 'secret', 'refresh_token']);
});

it('hardens DNA file validation against undersized, unrecognized, and script payloads while accepting valid formats', function (): void {
    $validator = new DnaFileValidator();

    expect($validator->validate('rs1 1 100 AA')['valid'])->toBeFalse()
        ->and($validator->validate(str_repeat('<script>alert(1)</script>', 100))['valid'])->toBeFalse();

    $header = "# This data file generated by 23andMe\n# rsid\tchromosome\tposition\tgenotype\n";
    $rows = '';
    for ($i = 1; $i <= 80; $i++) {
        $rows .= "rs{$i}\t1\t".($i * 1000)."\tAG\n";
    }
    $valid23 = $validator->validate($header.$rows);

    expect($valid23['valid'])->toBeTrue()
        ->and($valid23['format'])->toBe('23andme')
        ->and($valid23['snp_count'])->toBe(80);

    expect($validator->detectFormat('rsid,chromosome,position,allele1,allele2'))->toBe('ancestry')
        ->and($validator->detectFormat('RSID,Chr,Position,Result'))->toBe('myheritage')
        ->and($validator->detectFormat('RSID,CHROMOSOME,POSITION,RESULT'))->toBe('ftdna');
});

it('rejects tampered, wrong-secret, replayed, and future-skewed webhook signatures', function (): void {
    $signer = new WebhookSigner();
    $payload = '{"id":"evt_1","type":"person.merged"}';
    $secret = 'whsec_live_regression_key';
    $now = time();
    $validSig = $signer->sign($payload, $secret, $now);

    expect($signer->verify($payload, $secret, $now, $validSig, 300))->toBeTrue()
        ->and($signer->verify($payload.' ', $secret, $now, $validSig, 300))->toBeFalse()
        ->and($signer->verify($payload, 'wrong_secret', $now, $validSig, 300))->toBeFalse()
        ->and($signer->verify($payload, $secret, $now - 301, $signer->sign($payload, $secret, $now - 301), 300))->toBeFalse()
        ->and($signer->verify($payload, $secret, $now + 301, $signer->sign($payload, $secret, $now + 301), 300))->toBeFalse();
});

it('hides private tree existence from guests and prevents living-person disclosure via include_living query override', function (): void {
    $owner = User::factory()->create();
    $team = Team::factory()->create(['user_id' => $owner->id]);
    $owner->forceFill(['current_team_id' => $team->id])->save();

    app(TeamContext::class)->set($team->id);
    $root = app(CreatePerson::class)->execute(['given_name' => 'DeceasedRoot', 'death_date' => '1950-01-01', 'is_public' => true]);
    $livingChild = app(CreatePerson::class)->execute(['given_name' => 'SecretLivingChild', 'is_public' => true]);
    app(CreateRelationship::class)->execute(['person_id' => $root->id, 'related_person_id' => $livingChild->id, 'type' => 'parent']);

    $privateTree = app(CreateTree::class)->execute(['name' => 'Hidden Private Tree', 'is_public' => false, 'user_id' => $owner->id]);
    $publicTreeView = app(CreateTreeView::class)->execute(['name' => 'Public Tree', 'root_person_id' => $root->id, 'is_public' => true, 'status' => 'active']);
    app(TeamContext::class)->clear();

    // Guest gets 404 (not 403) so private resource UUID existence is not leaked
    $this->getJson("/api/v1/genealogy/genealogy-core/{$privateTree->id}")->assertNotFound();

    // Guest requesting public tree graph with include_living=1 still cannot see living relatives
    $this->getJson("/api/v1/genealogy/tree-viewer/{$publicTreeView->id}/graph?include_living=1")
        ->assertOk()
        ->assertDontSee('SecretLivingChild');
});
